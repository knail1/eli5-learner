const GLYPHS: Record<string, boolean[][]> = Object.fromEntries(
  Object.entries(G).map(([ch, rows]) => [ch, rows.split('|').map((r) => [...r].map((c) => c === '#'))]),
);

export const GLYPH_W = 5;
export const GLYPH_H = 7;

export function glyph(ch: string): boolean[][] {
  return GLYPHS[ch.toUpperCase()] ?? (GLYPHS['?'] as boolean[][]);
}

export function hasGlyph(ch: string): boolean {
  return GLYPHS[ch.toUpperCase()] !== undefined;
}
